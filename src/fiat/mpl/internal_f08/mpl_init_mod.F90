MODULE MPL_INIT_MOD

!**** MPL_INIT - Initialises the Message passing environment

!     Purpose.
!     --------
!     Must be called before any other MPL routine.

!**   Interface.
!     ----------
!        CALL MPL_INIT

!        Input required arguments :
!        -------------------------
!           none

!        Input optional arguments :
!        -------------------------
!           KOUTPUT  -  Level of printing for MPL routines
!                       =0: none
!                       =1: intermediate (default)
!                       =2: full trace
!           KUNIT    -  Fortran Unit to receive printed trace
!           LDINFO   -  = .TRUE.  : Print informative msgs from MPL_INIT (default) 
!                       = .FALSE. : Do not print
!           LDENV    -  = .TRUE.  : Propagate environment variables across participating tasks (default)
!                       = .FALSE. : Do not propagate
!

!        Output required arguments :
!        -------------------------
!           none

!        Output optional arguments :
!        -------------------------
!           KERROR   -  return error code.     If not supplied, 
!                       MPL_INIT aborts when an error is detected.
!           KPROCS   -  Number of processes which have been initialised
!                       in the MPI_COMM_WORLD communicator
!
!     Author.
!     -------
!        D.Dent, M.Hamrud     ECMWF

!     Modifications.
!     --------------
!        Original: 2000-09-01
!        R. El Khatib  14-May-2007 Do not propagate environment if NECSX
!        S. Saarinen 04-Oct-2009 Reduced output & redefined MPL_COMM_OML(1)
!        P. Marguinaud 01-Jan-2011 Add LDENV argument
!        R. El Khatib  24-May-2011 Make MPI2 the default expectation.
!        P. Towers     3-Jul-2014 Add call to ec_cray_meminfo
!     ------------------------------------------------------------------

USE EC_PARKIND, ONLY : JPIM
USE OML_MOD,    ONLY : OML_INIT, OML_GET_MAX_THREADS

USE MPL_MPI,               ONLY : MPI_COMM, MPI_THREAD_SINGLE, MPI_THREAD_MULTIPLE, MPI_COMM_WORLD, &
 &                                MPI_BYTE, MPI_INTEGER
USE MPL_DATA_MODULE,       ONLY : MPL_COMM_OML, MPL_NUMPROC, MPL_NODE, MPL_NNODES, MPL_TASK_PER_NODE, &
 &                                MPL_NUMPROC,MPL_MAX_TASK_PER_NODE, MPL_NODE_TASKS, MPL_OUTPUT, MPL_RANK, &
 &                                MPL_OPPONENT, MPL_MYNODE, MPL_UNIT, LFULLNODES, MPL_NCPU_PER_NODE, &
 &                                LTHSAFEMPI, LINITMPI_VIA_MPL, LMPLUSERCOMM, LUSEHLMPI, MPLUSERCOMM, MPL_COMM, &
 &                                MPL_MBX_SIZE, MPL_WORLD_RANK, MPL_WORLD_SIZE, MPL_METHOD, MPL_IDS, &
 &                                JP_BLOCKING_STANDARD, JP_BLOCKING_BUFFERED
USE MPL_MESSAGE_MOD,       ONLY : MPL_MESSAGE
USE MPL_BUFFER_METHOD_MOD, ONLY : MPL_BUFFER_METHOD
USE MPL_TOUR_TABLE_MOD,    ONLY : MPL_TOUR_TABLE 
USE MPL_LOCOMM_CREATE_MOD, ONLY : MPL_LOCOMM_CREATE
USE MPL_ARG_MOD,           ONLY : MPL_IARGC
USE EC_ENV_MOD,            ONLY : EC_PUTENV, EC_NUMENV, EC_ENVIRON

IMPLICIT NONE

PUBLIC MPL_INIT
PUBLIC MPL_INIT_THREAD
PUBLIC MPL_UPDATE_COMMS

PRIVATE

CONTAINS 

SUBROUTINE MPL_INIT(KOUTPUT,KUNIT,KERROR,KPROCS,LDINFO,LDENV)

#ifdef USE_8_BYTE_WORDS
  USE MPI4TO8, ONLY : &
    MPI_INITIALIZED => MPI_INITIALIZED8, MPI_INIT => MPI_INIT8, &
    MPI_COMM_SIZE => MPI_COMM_SIZE8,     MPI_COMM_RANK => MPI_COMM_RANK8, &
    MPI_BCAST => MPI_BCAST8
#endif



INTEGER(KIND=JPIM),INTENT(IN),OPTIONAL :: KOUTPUT,KUNIT
INTEGER(KIND=JPIM),INTENT(OUT),OPTIONAL :: KERROR,KPROCS
LOGICAL,INTENT(IN),OPTIONAL :: LDINFO,LDENV
INTEGER(KIND=JPIM) :: IERROR,IP,ICOMM,IRANK,JNODE,JROC,ISTA
INTEGER(KIND=JPIM) :: IMAX_THREADS, IRET, IROOT, INUM(2), ICOUNT
INTEGER(KIND=JPIM) :: IREQUIRED,IPROVIDED
INTEGER(KIND=JPIM) :: IWORLD_RANK, IWORLD_SIZE
INTEGER(KIND=JPIM) :: IME
LOGICAL            :: LLABORT=.TRUE., LLINFO
LOGICAL            :: LLINIT
LOGICAL            :: LLENV
CHARACTER(LEN=12)  :: CL_MBX_SIZE
CHARACTER(LEN=12)  :: CL_ARCH
CHARACTER(LEN=12)  :: CL_TASKSPERNODE
CHARACTER(LEN=1024):: CLENV
CHARACTER(LEN=20)  :: CL_METHOD,CL_HOST
CHARACTER(LEN=1)   :: CL_SET
TYPE(MPI_COMM)      :: MPL_COMM_INTERNAL

IF(PRESENT(KOUTPUT)) THEN
  MPL_OUTPUT=MAX(0,KOUTPUT)
ELSE
  MPL_OUTPUT=1
ENDIF

IF(PRESENT(KUNIT)) THEN
  MPL_UNIT=MAX(0,KUNIT)
ELSE
  MPL_UNIT=6
ENDIF

IF(PRESENT(LDINFO)) THEN
  LLINFO = LDINFO
ELSE
  LLINFO = .TRUE.
ENDIF

IF(PRESENT(LDENV)) THEN
  LLENV = LDENV
ELSE
  LLENV = .TRUE.
ENDIF

IF(MPL_NUMPROC /= -1) THEN
!!  We do not want this extra message
!!  CALL MPL_MESSAGE(CDMESSAGE=' MPL_INIT CALLED MULTIPLE TIMES ')
  IF(PRESENT(KERROR)) THEN
    KERROR=0
  ENDIF
  IF(PRESENT(KPROCS)) THEN
    KPROCS=MPL_NUMPROC
  ENDIF
  RETURN
ENDIF

CALL MPI_INITIALIZED(LLINIT, IRET)

IF (.NOT.LLINIT) THEN

  CALL GET_ENVIRONMENT_VARIABLE('ARCH',CL_ARCH)


#ifndef MPI1
  IREQUIRED = MPI_THREAD_MULTIPLE
  IPROVIDED = MPI_THREAD_SINGLE
  CALL MPI_INIT_THREAD(IREQUIRED,IPROVIDED,IERROR)
  IF (IERROR /= 0) CALL ABOR1 ('MPL_INIT: MPI_INIT_THREAD FAILED')
  LTHSAFEMPI = (IPROVIDED >= IREQUIRED)
#else
  CALL MPI_INIT(IERROR)
  IF (IERROR /= 0) CALL ABOR1 ('MPL_INIT: MPI_INIT FAILED')
  LTHSAFEMPI = .FALSE.
#endif

CALL MPI_COMM_RANK(MPI_COMM_WORLD, IME, IERROR)

! Print out thread safety etc. messages -- must use MPI_Comm_rank since MPL not initialized just yet
IF (IME == 0 .AND. LLINFO ) THEN
   WRITE(MPL_UNIT,'(4(A,I0),1(A,L1))') &
        & 'MPL_INIT : MPI_THREAD_MULTIPLE=',MPI_THREAD_MULTIPLE,' , MPI_THREAD_SINGLE=',MPI_THREAD_SINGLE,&
        &         ' , IREQUIRED=',IREQUIRED,' , IPROVIDED=',IPROVIDED,' , LTHSAFEMPI=',LTHSAFEMPI
ENDIF

  LINITMPI_VIA_MPL = .TRUE.
!  CALL ec_mpi_atexit() ! ifsaux/support/endian.c: to make sure MPI_FINALIZE gets called

ELSE
  IERROR = 0
ENDIF

IF(PRESENT(KERROR)) THEN
  KERROR=IERROR
ELSE
  IF(IERROR /= 0) THEN
    CALL MPL_MESSAGE(CDMESSAGE=' MPL_INIT ERROR ',KERROR=IERROR,LDABORT=LLABORT)
  ENDIF
ENDIF

! If LMPLUSERCOMM is not set use MPI_COMM_WORLD
!mps: Sami Saarinen, 29-Nov-2016
! Must be set *AFTER* MPI_INIT*() has ben called (or LLINIT is true)
! Otherwise MPI_COMM_WORLD not defined (at least not in OpenMPI)
IF(LMPLUSERCOMM) THEN
   MPL_COMM = MPLUSERCOMM
ELSE
   MPL_COMM = MPI_COMM_WORLD%MPI_VAL
ENDIF
MPL_COMM_INTERNAL%MPI_VAL = MPL_COMM

CALL MPI_COMM_SIZE(MPL_COMM_INTERNAL,MPL_NUMPROC,IERROR)

IF(PRESENT(KPROCS)) THEN
  KPROCS=MPL_NUMPROC
ENDIF

ALLOCATE (MPL_IDS(MPL_NUMPROC))
DO IP=1,MPL_NUMPROC
  MPL_IDS(IP)=IP
ENDDO

CALL MPI_COMM_RANK(MPL_COMM_INTERNAL, IRANK, IERROR)
MPL_RANK=IRANK+1

IF (MPL_RANK == 1) THEN
  ! Clean up possible lockfile which gets created within MPL_ABORT
  CALL TABORT_DELETE_LOCKFILE()
ENDIF

LLINFO = LLINFO .AND. (MPL_RANK <= 1)

IF (LLINFO) THEN
   IF(LMPLUSERCOMM) THEN
      WRITE(MPL_UNIT,'(2(A,I0))')'MPL_INIT : MPL_COMM=',MPL_COMM, ' (non-default) , MPL_NUMPROC=',MPL_NUMPROC
   ELSE
      WRITE(MPL_UNIT,'(2(A,I0))')'MPL_INIT : MPL_COMM=',MPL_COMM, ' (default) , MPL_NUMPROC=',MPL_NUMPROC
   ENDIF
ENDIF

!-- Propagate environment variables & argument lists
!   Here we have to be careful and use MPI_BCAST directly (not MPL_BROADCAST) since
!   1) MPL_BUFFER_METHOD has not been called
!   2) MPL_COMM_OML has not been initialized since it is possible that only the 
!      master proc knows the # of threads (i.e. OMP_NUM_THREADS may be set only for master)

! Do not propagate on nec machine because the environment variables could be mpi-task-specific.

IF (MPL_NUMPROC > 1 .AND. LLENV) THEN
  IROOT = 0
  !-- Progate environment variables
  INUM(1) = 0 ! The number of environment variables
  INUM(2) = 0 ! Do not (=0) or do (=1) overwrite if particular environment variable already exists (0 = default)
  IF (MPL_RANK == 1) THEN ! Master proc inquires
    INUM(1) = EC_NUMENV()
    CALL GET_ENVIRONMENT_VARIABLE("EC_OVERWRITE_ENV",CLENV)
    IF( CLENV == '1' ) INUM(2) = 1
  ENDIF
  ! The following broadcast does not use "mailbox" nor attached buffer, both potentially yet to be allocated
  CALL MPI_BCAST(INUM,2,MPI_INTEGER,IROOT,MPL_COMM_INTERNAL,IERROR)
  ICOUNT = LEN(CLENV)
  DO IP=1,INUM(1)
    IF (MPL_RANK == 1) CALL EC_ENVIRON(IP,CLENV)
    ! The following broadcast does not use "mailbox" nor attached buffer, both potentially yet to be allocated
    CALL MPI_BCAST(CLENV,ICOUNT,MPI_BYTE,IROOT,MPL_COMM_INTERNAL,IERROR)
    IF (MPL_RANK > 1) THEN
      IF (INUM(2) == 1) THEN
        CALL EC_PUTENV(CLENV,OVERWRITE=.TRUE.) ! ../support/env.c ; Unconditionally overwrite, even if already exists
      ELSE
        CALL EC_PUTENV(CLENV,OVERWRITE=.FALSE.) ! ../support/env.c ; Do not overwrite, if exists
      ENDIF
    ENDIF
  ENDDO
  !-- Propagate argument list (all under the bonnet using MPL_ARG_MOD-module)
  INUM = MPL_IARGC()
ENDIF

CALL OML_INIT()
IMAX_THREADS = OML_GET_MAX_THREADS()
ALLOCATE(MPL_COMM_OML(IMAX_THREADS))

IF (LMPLUSERCOMM) THEN
   MPL_COMM_OML(1) = MPLUSERCOMM
   ISTA = 2
ELSE
   ISTA = 1
ENDIF

IF (MPL_NUMPROC > 1) THEN
   DO IP=ISTA,IMAX_THREADS
      CALL MPL_LOCOMM_CREATE(MPL_NUMPROC,MPL_COMM_OML(IP))
   ENDDO
   MPL_COMM = MPL_COMM_OML(1) ! i.e. not necessary MPI_COMM_WORLD anymore
   MPL_COMM_INTERNAL%MPI_VAL = MPL_COMM
ELSE
   MPL_COMM_OML(ISTA:IMAX_THREADS)=MPL_COMM
ENDIF

CL_METHOD=' '
CALL GET_ENVIRONMENT_VARIABLE('MPL_METHOD',CL_METHOD)
IF (CL_METHOD == 'JP_BLOCKING_STANDARD' ) THEN
  MPL_METHOD=JP_BLOCKING_STANDARD
ELSE
  MPL_METHOD=JP_BLOCKING_BUFFERED
ENDIF
MPL_MBX_SIZE=1000000
CL_MBX_SIZE=' '
CALL GET_ENVIRONMENT_VARIABLE('MPL_MBX_SIZE',CL_MBX_SIZE)
IF (CL_MBX_SIZE /= ' ') THEN
  READ(CL_MBX_SIZE,*) MPL_MBX_SIZE
ENDIF
IF (CL_METHOD == 'JP_BLOCKING_STANDARD' ) THEN
  IF (LLINFO) WRITE(MPL_UNIT,'(A,I0)')'MPL_INIT : MPL_METHOD=JP_BLOCKING_STANDARD , MPL_MBX_SIZE=',MPL_MBX_SIZE
ELSE
  IF (LLINFO) WRITE(MPL_UNIT,'(A,I0)')'MPL_INIT : MPL_METHOD=JP_BLOCKING_BUFFERED , MPL_MBX_SIZE=',MPL_MBX_SIZE
ENDIF

CALL MPL_BUFFER_METHOD(KMP_TYPE=MPL_METHOD,KMBX_SIZE=MPL_MBX_SIZE,LDINFO=.FALSE.)
LUSEHLMPI = .TRUE.

CALL MPI_COMM_RANK (MPI_COMM_WORLD, IWORLD_RANK, IERROR)
CALL MPI_COMM_SIZE (MPI_COMM_WORLD, IWORLD_SIZE, IERROR)

#ifdef LINUX
CALL LINUX_BIND (IWORLD_RANK, IWORLD_SIZE)
#endif

!-- World-wide tasks
MPL_WORLD_RANK = IWORLD_RANK
MPL_WORLD_SIZE = IWORLD_SIZE

!!!! If you are not at ECMWF this may need changing!!!!
CALL GET_ENVIRONMENT_VARIABLE('EC_TASKS_PER_NODE',CL_TASKSPERNODE)
IF (CL_TASKSPERNODE(1:1) == ' ' ) THEN
   CALL GET_ENVIRONMENT_VARIABLE('HOST',CL_HOST)
   IF(CL_HOST(1:3) == 'cck') THEN ! KNL
      MPL_NCPU_PER_NODE=64
   ELSEIF(CL_HOST(1:3) == 'cct') THEN ! Test-cluster
      MPL_NCPU_PER_NODE=24
   ELSEIF(CL_HOST(1:2) == 'cc') THEN ! cca/ccb
      MPL_NCPU_PER_NODE=36
   ELSEIF(CL_HOST(1:3) == 'lxg') THEN ! GPU-cluster
      MPL_NCPU_PER_NODE=24
   ELSEIF (CL_HOST(1:2) == 'c1') THEN
      MPL_NCPU_PER_NODE=64
   ELSEIF(CL_HOST(1:3) == 'hpc') THEN
      MPL_NCPU_PER_NODE=32
   ELSE
      MPL_NCPU_PER_NODE=1
      !IF(LLINFO) WRITE(MPL_UNIT,'(A)')'MPL_INIT : MPL_NCPU_PER_NODE = 1 (CAUTION: could not be inferred from hostname!)'
   ENDIF
ELSE
   READ(CL_TASKSPERNODE,*) MPL_NCPU_PER_NODE  
ENDIF
MPL_MAX_TASK_PER_NODE=MAX(1, MPL_NCPU_PER_NODE/IMAX_THREADS)
LFULLNODES=MOD(MPL_NUMPROC,MPL_MAX_TASK_PER_NODE) == 0
MPL_NNODES=(MPL_NUMPROC-1)/MPL_MAX_TASK_PER_NODE+1

ALLOCATE(MPL_TASK_PER_NODE(MPL_NNODES))
ALLOCATE(MPL_NODE(MPL_NUMPROC))
ALLOCATE(MPL_NODE_TASKS(MPL_NNODES,MPL_MAX_TASK_PER_NODE))
MPL_NODE_TASKS(:,:)=-99
ICOUNT=0
DO JNODE=1,MPL_NNODES
  DO JROC=1,MPL_MAX_TASK_PER_NODE
    ICOUNT=ICOUNT+1
    IF (ICOUNT<=MPL_NUMPROC) THEN
       MPL_NODE(ICOUNT)=JNODE
       MPL_TASK_PER_NODE(JNODE) = JROC
       MPL_NODE_TASKS(JNODE,JROC) = ICOUNT
    ENDIF
  ENDDO
ENDDO
MPL_MYNODE=(MPL_RANK-1)/MPL_MAX_TASK_PER_NODE+1
!WRITE(MPL_UNIT,*) 'MPL_INIT : NCPU_PER_NODE,MPL_MAX_TASK_PER_NODE,MPL_NNODES,MPL_MYNODE ',&
! & MPL_NCPU_PER_NODE,MPL_MAX_TASK_PER_NODE,MPL_NNODES,MPL_MYNODE
!WRITE(MPL_UNIT,*) 'MPL_INIT : MPL_NODE_TASKS(MPL_MYNODE,1:MPL_TASK_PER_NODE(MPL_MYNODE)) ', &
! & MPL_NODE_TASKS(MPL_MYNODE,1:MPL_TASK_PER_NODE(MPL_MYNODE))

ALLOCATE(MPL_OPPONENT(MPL_NUMPROC+1))
CALL MPL_TOUR_TABLE(MPL_OPPONENT)

RETURN
END SUBROUTINE MPL_INIT

SUBROUTINE MPL_INIT_THREAD(KREQUIRED,KPROVIDED,KOUTPUT,KUNIT,KERROR,KPROCS,LDINFO,LDENV)

!**** MPL_INIT_THREAD - Initialises MPI with an explicit thread level, then MPL

!     Purpose.
!     --------
!     Negotiates the MPI thread support level, checks it against the
!     OpenMP configuration and then calls MPL_INIT, which finds MPI
!     already initialised and leaves LTHSAFEMPI untouched.
!     MPL_INIT itself is unchanged, so existing callers are not affected.

!**   Interface.
!     ----------
!        CALL MPL_INIT_THREAD

!        Input optional arguments :
!        -------------------------
!           KREQUIRED -  Required MPI thread level (MPI_THREAD_SINGLE,
!                        MPI_THREAD_FUNNELED, MPI_THREAD_SERIALIZED or
!                        MPI_THREAD_MULTIPLE). If not supplied, the
!                        environment variable MPL_MPI_THREAD_LEVEL
!                        (SINGLE, FUNNELED, SERIALIZED or MULTIPLE) is
!                        used, otherwise MPI_THREAD_MULTIPLE (default).
!           KOUTPUT, KUNIT, LDINFO, LDENV - as for MPL_INIT

!        Output optional arguments :
!        -------------------------
!           KPROVIDED -  MPI thread level provided by the MPI library
!           KERROR, KPROCS - as for MPL_INIT

!     Checks.
!     -------
!        provided < required : warning
!        provided < MPI_THREAD_FUNNELED with more than one OpenMP thread :
!                     abort if more than one MPI task, warning otherwise
!        LTHSAFEMPI = (provided >= MPI_THREAD_MULTIPLE)
!     ------------------------------------------------------------------

#ifdef USE_8_BYTE_WORDS
  USE MPI4TO8, ONLY : &
    MPI_INITIALIZED => MPI_INITIALIZED8, MPI_INIT => MPI_INIT8, &
    MPI_COMM_SIZE => MPI_COMM_SIZE8,     MPI_COMM_RANK => MPI_COMM_RANK8
#endif

USE MPL_MPI, ONLY : MPI_THREAD_SINGLE, MPI_THREAD_FUNNELED, MPI_THREAD_SERIALIZED, &
 &                   MPI_THREAD_MULTIPLE, MPI_COMM_WORLD
USE MPL_DATA_MODULE, ONLY : MPL_NUMPROC, MPL_THREAD_REQUIRED, MPL_THREAD_PROVIDED, &
 &                          LTHSAFEMPI, LINITMPI_VIA_MPL

INTEGER(KIND=JPIM),INTENT(IN),OPTIONAL :: KREQUIRED
INTEGER(KIND=JPIM),INTENT(OUT),OPTIONAL :: KPROVIDED
INTEGER(KIND=JPIM),INTENT(IN),OPTIONAL :: KOUTPUT,KUNIT
INTEGER(KIND=JPIM),INTENT(OUT),OPTIONAL :: KERROR,KPROCS
LOGICAL,INTENT(IN),OPTIONAL :: LDINFO,LDENV

INTEGER(KIND=JPIM) :: IREQUIRED,IREQ,IPROVIDED,IERROR,IME,ISIZE,IUNIT,IMAX_THREADS,J,IC
LOGICAL            :: LLINIT,LLINFO
CHARACTER(LEN=32)  :: CLLEVEL

IF(MPL_NUMPROC /= -1) THEN
  ! MPL already initialised: behave like MPL_INIT
  IF(PRESENT(KPROVIDED)) KPROVIDED=MPL_THREAD_PROVIDED
  IF(PRESENT(KERROR)) KERROR=0
  IF(PRESENT(KPROCS)) KPROCS=MPL_NUMPROC
  RETURN
ENDIF

IUNIT=6
IF(PRESENT(KUNIT)) IUNIT=MAX(0,KUNIT)
LLINFO=.TRUE.
IF(PRESENT(LDINFO)) LLINFO=LDINFO

!-- Required thread level: argument, then environment, then MPI_THREAD_MULTIPLE
IF(PRESENT(KREQUIRED)) THEN
  IREQUIRED=KREQUIRED
ELSE
  CLLEVEL=' '
  CALL GET_ENVIRONMENT_VARIABLE('MPL_MPI_THREAD_LEVEL',CLLEVEL)
  CLLEVEL=ADJUSTL(CLLEVEL)
  DO J=1,LEN_TRIM(CLLEVEL)
    IC=IACHAR(CLLEVEL(J:J))
    IF(IC >= IACHAR('a') .AND. IC <= IACHAR('z')) CLLEVEL(J:J)=ACHAR(IC-32)
  ENDDO
  SELECT CASE (TRIM(CLLEVEL))
  CASE ('')
    IREQUIRED=MPI_THREAD_MULTIPLE
  CASE ('SINGLE','MPI_THREAD_SINGLE')
    IREQUIRED=MPI_THREAD_SINGLE
  CASE ('FUNNELED','MPI_THREAD_FUNNELED')
    IREQUIRED=MPI_THREAD_FUNNELED
  CASE ('SERIALIZED','MPI_THREAD_SERIALIZED')
    IREQUIRED=MPI_THREAD_SERIALIZED
  CASE ('MULTIPLE','MPI_THREAD_MULTIPLE')
    IREQUIRED=MPI_THREAD_MULTIPLE
  CASE DEFAULT
    CALL ABOR1('MPL_INIT_THREAD: INVALID MPL_MPI_THREAD_LEVEL='//TRIM(CLLEVEL))
  END SELECT
ENDIF

IF(IREQUIRED < MPI_THREAD_SINGLE .OR. IREQUIRED > MPI_THREAD_MULTIPLE) THEN
  CALL ABOR1('MPL_INIT_THREAD: INVALID REQUIRED THREAD LEVEL')
ENDIF

!-- Initialise MPI, or query the level if MPI was already initialised
CALL MPI_INITIALIZED(LLINIT,IERROR)
IF (IERROR /= 0) CALL ABOR1('MPL_INIT_THREAD: MPI_INITIALIZED FAILED')

IF (.NOT.LLINIT) THEN
#ifndef MPI1
  IREQ=IREQUIRED ! keep IREQUIRED intact whatever MPI_INIT_THREAD does to its argument
  IPROVIDED=MPI_THREAD_SINGLE
  CALL MPI_INIT_THREAD(IREQ,IPROVIDED,IERROR)
  IF (IERROR /= 0) CALL ABOR1('MPL_INIT_THREAD: MPI_INIT_THREAD FAILED')
#else
  CALL MPI_INIT(IERROR)
  IF (IERROR /= 0) CALL ABOR1('MPL_INIT_THREAD: MPI_INIT FAILED')
  IPROVIDED=MPI_THREAD_SINGLE
#endif
  LINITMPI_VIA_MPL=.TRUE.
ELSE
#ifndef MPI1
  CALL MPI_QUERY_THREAD(IPROVIDED,IERROR)
  IF (IERROR /= 0) CALL ABOR1('MPL_INIT_THREAD: MPI_QUERY_THREAD FAILED')
#else
  IPROVIDED=MPI_THREAD_SINGLE
#endif
ENDIF

MPL_THREAD_REQUIRED=IREQUIRED
MPL_THREAD_PROVIDED=IPROVIDED
LTHSAFEMPI=(IPROVIDED >= MPI_THREAD_MULTIPLE)

CALL MPI_COMM_RANK(MPI_COMM_WORLD,IME,IERROR)
CALL MPI_COMM_SIZE(MPI_COMM_WORLD,ISIZE,IERROR)

CALL OML_INIT()
IMAX_THREADS=OML_GET_MAX_THREADS()

!-- Print thread level information (MPL not initialised yet: use the world rank)
IF (IME == 0 .AND. LLINFO) THEN
  WRITE(IUNIT,'(6A,I0,A,L1)') 'MPL_INIT_THREAD : REQUIRED=',TRIM(MPL_THREAD_LEVEL_NAME(IREQUIRED)), &
   & ' , PROVIDED=',TRIM(MPL_THREAD_LEVEL_NAME(IPROVIDED)),' , ',&
   & 'OML_MAX_THREADS=',IMAX_THREADS,' , LTHSAFEMPI=',LTHSAFEMPI
ENDIF

!-- Checks
IF (IPROVIDED < IREQUIRED .AND. IME == 0) THEN
  WRITE(IUNIT,'(4A)') 'MPL_INIT_THREAD : WARNING : MPI PROVIDES ',TRIM(MPL_THREAD_LEVEL_NAME(IPROVIDED)), &
   & ' BUT REQUIRED IS ',TRIM(MPL_THREAD_LEVEL_NAME(IREQUIRED))
ENDIF

IF (IMAX_THREADS > 1 .AND. IPROVIDED < MPI_THREAD_FUNNELED) THEN
  IF (ISIZE > 1) THEN
    CALL ABOR1('MPL_INIT_THREAD: MPI_THREAD_SINGLE IS NOT SUFFICIENT WITH MORE THAN ONE OPENMP THREAD')
  ELSEIF (IME == 0) THEN
    WRITE(IUNIT,'(A)') 'MPL_INIT_THREAD : WARNING : MPI_THREAD_SINGLE WITH MORE THAN ONE OPENMP THREAD'
  ENDIF
ENDIF

IF(PRESENT(KPROVIDED)) KPROVIDED=IPROVIDED

!-- MPI is initialised now: MPL_INIT only sets up the MPL context
CALL MPL_INIT(KOUTPUT=KOUTPUT,KUNIT=KUNIT,KERROR=KERROR,KPROCS=KPROCS,LDINFO=LDINFO,LDENV=LDENV)

END SUBROUTINE MPL_INIT_THREAD

FUNCTION MPL_THREAD_LEVEL_NAME(KLEVEL) RESULT(CDNAME)

USE MPL_MPI, ONLY : MPI_THREAD_SINGLE, MPI_THREAD_FUNNELED, MPI_THREAD_SERIALIZED, &
 &                   MPI_THREAD_MULTIPLE

INTEGER(KIND=JPIM),INTENT(IN) :: KLEVEL
CHARACTER(LEN=32) :: CDNAME

IF (KLEVEL == MPI_THREAD_SINGLE) THEN
  CDNAME='MPI_THREAD_SINGLE'
ELSEIF (KLEVEL == MPI_THREAD_FUNNELED) THEN
  CDNAME='MPI_THREAD_FUNNELED'
ELSEIF (KLEVEL == MPI_THREAD_SERIALIZED) THEN
  CDNAME='MPI_THREAD_SERIALIZED'
ELSEIF (KLEVEL == MPI_THREAD_MULTIPLE) THEN
  CDNAME='MPI_THREAD_MULTIPLE'
ELSE
  WRITE(CDNAME,'(A,I0,A)') 'UNKNOWN(',KLEVEL,')'
ENDIF

END FUNCTION MPL_THREAD_LEVEL_NAME

SUBROUTINE MPL_UPDATE_COMMS(KCOMM)

  USE MPL_MPI, ONLY : MPI_COMM, MPI_COMM_NULL, MPI_COMM_WORLD, &
   &                 MPI_COMM_SELF, MPI_INTEGER
  USE MPL_DATA_MODULE, ONLY : MPL_NUMPROC, MPL_COMM_OML, MPL_COMM, MPL_RANK, MPL_IDS, &
   &                          MPL_OPPONENT, MPL_MYNODE, MPL_NODE, MPL_NNODES, &
   &                          MPL_TASK_PER_NODE, MPL_NODE_TASKS, MPL_MAX_TASK_PER_NODE, &
   &                          LFULLNODES, LMPLUSERCOMM, MPLUSERCOMM

  INTEGER(KIND=JPIM), INTENT(IN) :: KCOMM

  INTEGER(KIND=JPIM) :: IERROR
  INTEGER(KIND=JPIM) :: INPROCS, IRANK, INTHREADS
  INTEGER(KIND=JPIM) :: INNODES, INODE, ICOUNT
  INTEGER(KIND=JPIM) :: IP, IT, J, ICOMM
  INTEGER(KIND=JPIM) :: IOLDPARENT

  INTEGER(KIND=JPIM), ALLOCATABLE :: IOLDCOMMS(:)
  INTEGER(KIND=JPIM), ALLOCATABLE :: INEWCOMMS(:)
  INTEGER(KIND=JPIM), ALLOCATABLE :: IOLDNODES(:)
  INTEGER(KIND=JPIM), ALLOCATABLE :: INODELABELS(:)
  INTEGER(KIND=JPIM), ALLOCATABLE :: INEWNODE(:)
  INTEGER(KIND=JPIM), ALLOCATABLE :: INODECOUNTS(:)

  LOGICAL :: LOLDUSERCOMM
  TYPE(MPI_COMM) :: YLCOMM, YLNEW, YLOLD

  ! Preconditions: MPL is fully initialised; all old ranks participate;
  ! KCOMM is a non-null intracommunicator formed from the old context.
  ! No outstanding requests or concurrent MPL calls are permitted.

  IF (MPL_NUMPROC < 1) THEN
    CALL ABOR1('MPL_UPDATE_COMMS: MPL IS NOT INITIALISED')
    RETURN
  ENDIF

  IF (KCOMM == MPI_COMM_NULL%MPI_VAL) THEN
    CALL ABOR1('MPL_UPDATE_COMMS: NULL ROLE COMMUNICATOR')
    RETURN
  ENDIF

  IF (.NOT. ALLOCATED(MPL_COMM_OML)) THEN
    CALL ABOR1('MPL_UPDATE_COMMS: MISSING THREAD COMMUNICATORS')
    RETURN
  ENDIF

  INTHREADS = SIZE(MPL_COMM_OML)

  ! Preserve handles before replacing any module state.

  ALLOCATE(IOLDCOMMS(INTHREADS))
  ALLOCATE(INEWCOMMS(INTHREADS))

  IOLDCOMMS = MPL_COMM_OML
  LOLDUSERCOMM = LMPLUSERCOMM
  IOLDPARENT = MPLUSERCOMM

  ! This synchronises the transition; it does not complete requests.
  YLCOMM%MPI_VAL = KCOMM
  CALL MPI_BARRIER(YLCOMM, IERROR)
  IF (IERROR /= 0) GOTO 900

  CALL MPI_COMM_SIZE(YLCOMM, INPROCS, IERROR)
  IF (IERROR /= 0) GOTO 900

  CALL MPI_COMM_RANK(YLCOMM, IRANK, IERROR)
  IF (IERROR /= 0) GOTO 900

  ! Preserve the old node classification, restricted to this role.
  ! Do not assume that role rank zero starts a new physical node.

  ALLOCATE(IOLDNODES(INPROCS))
  ALLOCATE(INODELABELS(INPROCS))
  ALLOCATE(INEWNODE(INPROCS))
  ALLOCATE(INODECOUNTS(INPROCS))

  CALL MPI_ALLGATHER(MPL_MYNODE, 1, MPI_INTEGER, &
   &                IOLDNODES, 1, MPI_INTEGER, YLCOMM, IERROR)
  IF (IERROR /= 0) GOTO 900

  INNODES = 0
  INODECOUNTS = 0

  DO IP = 1, INPROCS
    INODE = 0

    DO J = 1, INNODES
      IF (INODELABELS(J) == IOLDNODES(IP)) THEN
        INODE = J
        EXIT
      ENDIF
    ENDDO

    IF (INODE == 0) THEN
      INNODES = INNODES + 1
      INODE = INNODES
      INODELABELS(INODE) = IOLDNODES(IP)
    ENDIF

    INEWNODE(IP) = INODE
    INODECOUNTS(INODE) = INODECOUNTS(INODE) + 1
  ENDDO

  ! Own every new internal communicator, including the first.
  ! The application's KCOMM remains borrowed and is never freed here.

  DO IT = 1, INTHREADS
    CALL MPI_COMM_DUP(YLCOMM, YLNEW, IERROR)
    INEWCOMMS(IT) = YLNEW%MPI_VAL
    IF (IERROR /= 0) GOTO 900
  ENDDO

  ! Release old internal communicators once each.
  ! MPI predefined communicators and the old borrowed parent survive.

  DO IT = 1, INTHREADS
    ICOMM = IOLDCOMMS(IT)

    IF (ICOMM == MPI_COMM_NULL%MPI_VAL) CYCLE
    IF (ICOMM == MPI_COMM_WORLD%MPI_VAL) CYCLE
    IF (ICOMM == MPI_COMM_SELF%MPI_VAL) CYCLE

    IF (LOLDUSERCOMM) THEN
      IF (ICOMM == IOLDPARENT) CYCLE
    ENDIF

    ! Use an immutable snapshot because MPI_COMM_FREE changes its argument.
    IF (ANY(IOLDCOMMS(1:IT-1) == ICOMM)) CYCLE

    YLOLD%MPI_VAL = ICOMM
    CALL MPI_COMM_FREE(YLOLD, IERROR)
    IF (IERROR /= 0) GOTO 900
  ENDDO

  ! Install the new communicator context.

  MPL_COMM_OML = INEWCOMMS
  MPL_COMM = INEWCOMMS(1)

  LMPLUSERCOMM = .TRUE.
  MPLUSERCOMM = KCOMM

  MPL_NUMPROC = INPROCS
  MPL_RANK = IRANK + 1

  ! Rebuild processor IDs and the communication tournament.

  IF (ALLOCATED(MPL_IDS)) DEALLOCATE(MPL_IDS)
  ALLOCATE(MPL_IDS(INPROCS))

  DO IP = 1, INPROCS
    MPL_IDS(IP) = IP
  ENDDO

  IF (ALLOCATED(MPL_OPPONENT)) DEALLOCATE(MPL_OPPONENT)
  ALLOCATE(MPL_OPPONENT(INPROCS + 1))
  CALL MPL_TOUR_TABLE(MPL_OPPONENT)

  ! Rebuild node tables using role-local rank numbering.
  ! Keep the original per-node capacity.

  IF (ALLOCATED(MPL_NODE)) DEALLOCATE(MPL_NODE)
  IF (ALLOCATED(MPL_TASK_PER_NODE)) DEALLOCATE(MPL_TASK_PER_NODE)
  IF (ALLOCATED(MPL_NODE_TASKS)) DEALLOCATE(MPL_NODE_TASKS)

  MPL_NNODES = INNODES

  ALLOCATE(MPL_NODE(INPROCS))
  ALLOCATE(MPL_TASK_PER_NODE(INNODES))
  ALLOCATE(MPL_NODE_TASKS(INNODES, MPL_MAX_TASK_PER_NODE))

  MPL_NODE = INEWNODE
  MPL_TASK_PER_NODE = 0
  MPL_NODE_TASKS = -99

  DO IP = 1, INPROCS
    INODE = MPL_NODE(IP)
    ICOUNT = MPL_TASK_PER_NODE(INODE) + 1

    IF (ICOUNT > MPL_MAX_TASK_PER_NODE) THEN
      CALL ABOR1('MPL_UPDATE_COMMS: INCONSISTENT NODE CAPACITY')
      RETURN
    ENDIF

    MPL_TASK_PER_NODE(INODE) = ICOUNT
    MPL_NODE_TASKS(INODE, ICOUNT) = IP
  ENDDO

  MPL_MYNODE = MPL_NODE(MPL_RANK)
  LFULLNODES = ALL(MPL_TASK_PER_NODE == MPL_MAX_TASK_PER_NODE)

  DEALLOCATE(IOLDCOMMS, INEWCOMMS)
  DEALLOCATE(IOLDNODES, INODELABELS, INEWNODE, INODECOUNTS)

  RETURN

900 CONTINUE

  ! A failure during this collective transition is fatal.
  ! Returning would expose a potentially partially changed context.
  CALL ABOR1('MPL_UPDATE_COMMS: MPI OPERATION FAILED')
  STOP

END SUBROUTINE MPL_UPDATE_COMMS

END MODULE MPL_INIT_MOD
